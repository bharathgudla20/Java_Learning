CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL
);

CREATE TABLE job_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES app_users(id),
    company VARCHAR(100) NOT NULL,
    role VARCHAR(100) NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('APPLIED','INTERVIEW','OFFER','REJECTED')),
    applied_on DATE NOT NULL,
    notes VARCHAR(1000)
);

CREATE INDEX idx_applications_owner_date ON job_applications(owner_id, applied_on DESC, id DESC);
